// Regenerates src/generated.ts from the Foundry build of contracts/ and the committed
// deployments/mantle-sepolia.json. Run after any change to contracts/src or the address book:
//   pnpm --filter @0xwh1sker/mantle-meme-sdk generate
// test/artifacts.test.ts fails if the committed file drifts from either source.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const contracts = `${root}contracts`;
const target = fileURLToPath(new URL("../src/generated.ts", import.meta.url));

execFileSync("forge", ["build"], { cwd: contracts, stdio: "inherit" });
const artifact = (name) =>
  JSON.parse(readFileSync(`${contracts}/out/${name}.sol/${name}.json`, "utf8"));
const launchpad = artifact("MemeLaunchpad");
const token = artifact("MemeToken");
const deployment = JSON.parse(readFileSync(`${root}deployments/mantle-sepolia.json`, "utf8"));

const json = (value) => JSON.stringify(value);
writeFileSync(
  target,
  `// Generated by scripts/generate.mjs from contracts/out and deployments/mantle-sepolia.json.
// Do not edit by hand; test/artifacts.test.ts checks it against a fresh forge build.

export const memeLaunchpadAbi = ${json(launchpad.abi)} as const;

export const memeTokenAbi = ${json(token.abi)} as const;

/** MemeToken creation code (with compiler metadata) that MemeLaunchpad deploys with CREATE2. */
export const memeTokenCreationCode = ${json(token.bytecode.object)} as const;

/** deployments/mantle-sepolia.json as committed in this repository. */
export const MEME_MANTLE_SEPOLIA = ${json(deployment)};
`,
);
execFileSync("pnpm", ["exec", "biome", "format", "--write", target], {
  cwd: root,
  stdio: "inherit",
});

// The Mantle Sepolia acceptance run of DESIGN §9.1 (items 1–8) on the real chain: the flow of
// `flow.ts`, which CI runs on an anvil fork (`acceptance.fork.test.ts`). It spends testnet MNT, so it
// is a script, not a test: vitest collects only `*.test.ts`, and CI never runs it.
//
//   node --experimental-transform-types --no-warnings \
//     --import ./packages/cli/test/fixtures/node-ts.mjs e2e/acceptance/sepolia.ts
//
// Env:
//   MANTLE_SEPOLIA_RPC_URL     the chain (with ACCEPTANCE_FORK=1: the chain the anvil fork forks)
//   ACCEPTANCE_RELAYER_KEY     the sponsor's relayer hot wallet (handed to `mantle-aa sponsor serve`
//                              through its environment; never written to a file)
//   MARKET_SIM_MNEMONIC_FILE   the market-sim mnemonic (or MARKET_SIM_MNEMONIC); EOAs 0..2 pay their
//                              own gas
//   ACCEPTANCE_RUN_DIR         homes, the sponsor's config, database and log, and the results
//                              (`run.log`, `results.json`, `transactions.md`); default under $TMPDIR
//   ACCEPTANCE_FORK=1          rehearsal: the same run against a local anvil fork with throwaway keys
//                              (the key and mnemonic variables are not read)
//
// The human's root key and the agent home are generated by the run and hold 0 MNT throughout.
// Every output is scrubbed of keys, the mnemonic, passwords and the RPC URL; at the end every file
// under the run directory is checked for them.
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { appendFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { mantleSepolia } from "@0xwh1sker/mantle-aa-sdk";
import { memeLaunchpadAbi } from "@0xwh1sker/mantle-meme-sdk";
import {
  type Address,
  createPublicClient,
  decodeFunctionData,
  erc20Abi,
  formatEther,
  type Hex,
  http,
  type LocalAccount,
  nonceManager,
  parseEther,
  toHex,
} from "viem";
import {
  english,
  generateMnemonic,
  generatePrivateKey,
  mnemonicToAccount,
  privateKeyToAccount,
} from "viem/accounts";
import { startFork } from "../launchpad/fork.js";
import { Acceptance, filesUnder, type RunTx, runStep, STEPS } from "./flow.js";

const EXPLORER = "https://sepolia.mantlescan.xyz/tx/";
const fork = process.env.ACCEPTANCE_FORK === "1";
const env = (name: string) => {
  const value = process.env[name];
  if (!value) throw new Error(`${name} is required`);
  return value;
};
const upstream = env("MANTLE_SEPOLIA_RPC_URL");
const dir =
  process.env.ACCEPTANCE_RUN_DIR ??
  join(tmpdir(), `meme-acceptance-${fork ? "fork" : "sepolia"}-${Date.now()}`);
mkdirSync(dir, { recursive: true, mode: 0o700 });

// Keys: from the environment on Sepolia; throwaway on the rehearsal fork.
const mnemonic = fork
  ? generateMnemonic(english)
  : (process.env.MARKET_SIM_MNEMONIC_FILE
      ? readFileSync(process.env.MARKET_SIM_MNEMONIC_FILE, "utf8")
      : env("MARKET_SIM_MNEMONIC")
    ).trim();
const relayerKey = (fork ? generatePrivateKey() : env("ACCEPTANCE_RELAYER_KEY")) as Hex;
const sim: LocalAccount[] = [0, 1, 2].map((addressIndex) =>
  mnemonicToAccount(mnemonic, { addressIndex, nonceManager }),
);
const simKeys = [0, 1, 2].map((addressIndex) =>
  toHex(mnemonicToAccount(mnemonic, { addressIndex }).getHdKey().privateKey as Uint8Array),
);
const SECRETS = [mnemonic, relayerKey, ...simKeys];

let a: Acceptance | undefined;
/** The rehearsal's anvil fork; stopped on every way out. */
let stopFork: (() => void) | undefined;
const scrub = (text: string) => {
  if (a) return a.scrub(text);
  let t = text.replaceAll(upstream, "<rpc-url>");
  for (const s of SECRETS) t = t.replace(new RegExp(s.replace(/^0x/, ""), "gi"), "<redacted>");
  return t;
};
const log = (line: string) => {
  const out = scrub(`${new Date().toISOString()} ${line}`);
  console.log(out);
  appendFileSync(join(dir, "run.log"), `${out}\n`);
};

interface StepResult {
  item: string;
  name: string;
  started: string;
  finished: string;
  ok: boolean;
  error?: string;
}

/**
 * A sent transaction: sender, status, position and what it cost the sender in wei (L2 gas + L1
 * fee + operator fee); `call` names the function, for a transaction the flow did not label.
 */
async function costOf(client: ReturnType<typeof createPublicClient>, hash: Hex) {
  const raw = (await client.request({
    method: "eth_getTransactionReceipt",
    params: [hash],
  } as never)) as Record<string, Hex | undefined> | null;
  const tx = await client.getTransaction({ hash });
  let call = "";
  try {
    call = decodeFunctionData({
      abi: [...erc20Abi, ...memeLaunchpadAbi],
      data: tx.input,
    }).functionName;
  } catch {}
  if (!raw) return { from: tx.from, status: "not mined", block: 0n, index: 0, fee: 0n, call };
  const big = (field: string) => BigInt(raw[field] ?? "0x0");
  return {
    from: raw.from as Address,
    status: raw.status === "0x1" ? "success" : "reverted",
    block: big("blockNumber"),
    index: Number(big("transactionIndex")),
    fee:
      big("gasUsed") * big("effectiveGasPrice") +
      big("l1Fee") +
      big("gasUsed") * big("operatorFeeScalar") * 100n +
      big("operatorFeeConstant"),
    call,
  };
}

async function main() {
  const startedAt = new Date();
  const commit = execFileSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).trim();
  const dirty = execFileSync("git", ["status", "--porcelain", "--untracked-files=no"], {
    encoding: "utf8",
  }).trim();
  log(`commit ${commit}; tracked tree ${dirty ? "DIRTY" : "clean"}; run dir ${dir}`);
  if (!fork && dirty)
    throw new Error("refusing a Sepolia run from a tree with uncommitted changes");

  let rpcUrl = upstream;
  if (fork) {
    const f = await startFork(upstream);
    stopFork = f.stop;
    rpcUrl = f.url;
  }
  const client = createPublicClient({
    chain: mantleSepolia,
    transport: http(rpcUrl, { timeout: 30_000, retryCount: 8 }),
  });
  assert.equal(await client.getChainId(), 5003, "Mantle Sepolia");
  const relayer = privateKeyToAccount(relayerKey).address;
  if (fork) {
    for (const who of [relayer, ...sim.map((s) => s.address)]) {
      await client.request({
        method: "anvil_setBalance" as never,
        params: [who, toHex(parseEther(who === relayer ? "3" : "0.5"))] as never,
      });
    }
  }
  const wallets: Record<string, Address> = {
    relayer,
    "market-sim 0": sim[0]?.address as Address,
    "market-sim 1": sim[1]?.address as Address,
    "market-sim 2": sim[2]?.address as Address,
  };
  const balance = (who: Address) => client.getBalance({ address: who });
  const before: Record<string, bigint> = {};
  for (const [name, who] of Object.entries(wallets)) {
    before[name] = await balance(who);
    log(`${name} ${who}: ${formatEther(before[name] as bigint)} MNT`);
  }
  assert.ok((before.relayer as bigint) >= parseEther("1"), "the relayer holds at least 1 MNT");
  for (const i of [0, 1, 2]) {
    assert.ok(
      (before[`market-sim ${i}`] as bigint) >= parseEther("0.2"),
      `market-sim ${i} holds 0.2 MNT`,
    );
  }

  a = new Acceptance({
    mode: fork ? "fork" : "sepolia",
    rpcUrl,
    relayerKey,
    sim,
    dir,
    // On Sepolia the daemon's defaults: the public RPC limits requests per IP.
    tickMs: fork ? 300 : 10_000,
    pollMs: fork ? 200 : 2_000,
    secrets: SECRETS,
    log,
  });
  const steps: StepResult[] = [];
  let failed = false;
  try {
    await a.start();
    for (const step of STEPS) {
      const started = new Date().toISOString();
      log(`START ${step.name}`);
      try {
        await runStep(a, step);
        steps.push({ ...step, started, finished: new Date().toISOString(), ok: true });
        log(`PASS  ${step.name}`);
      } catch (e) {
        const error = scrub(e instanceof Error ? (e.stack ?? e.message) : String(e));
        steps.push({ ...step, started, finished: new Date().toISOString(), ok: false, error });
        log(`FAIL  ${step.name}\n${error}`);
        failed = true;
        break;
      }
    }
  } finally {
    await a.stop();
    log("stopped the daemon, the sponsor and the proxies");
  }

  // The run's transactions: every one the market-sim EOAs and the relayer sent.
  const txs: (RunTx & Awaited<ReturnType<typeof costOf>> & { link: string })[] = [];
  for (const t of a.transactions()) {
    const { call, ...c } = await costOf(client, t.hash);
    const what =
      t.what ||
      (c.from.toLowerCase() === relayer.toLowerCase()
        ? "relayed for the account"
        : call === "approve"
          ? "market-sim approves the launchpad"
          : `market-sim ${call}`);
    txs.push({ ...t, what, ...c, call, link: `${EXPLORER}${t.hash}` });
  }
  txs.sort((x, y) => (x.block === y.block ? x.index - y.index : x.block < y.block ? -1 : 1));
  const after: Record<string, bigint> = {};
  for (const [name, who] of Object.entries(wallets)) after[name] = await balance(who);
  const spent = Object.fromEntries(
    Object.entries(wallets).map(([name, who]) => {
      const fees = txs.filter((t) => t.from.toLowerCase() === who.toLowerCase());
      return [
        name,
        {
          address: who,
          transactions: fees.length,
          spentMnt: formatEther((before[name] as bigint) - (after[name] as bigint)),
          feesMnt: formatEther(fees.reduce((s, t) => s + t.fee, 0n)),
        },
      ];
    }),
  );
  const human = {
    account: a.me,
    agentKey: a.agentKey ?? null,
    accountMnt: formatEther(await balance(a.me)),
    agentMnt: a.agentKey ? formatEther(await balance(a.agentKey)) : null,
  };
  log(`human/agent MNT at the end: ${JSON.stringify(human)}`);
  for (const [name, s] of Object.entries(spent)) log(`${name}: ${JSON.stringify(s)}`);

  const summary = {
    chain: fork ? "anvil fork of Mantle Sepolia (rehearsal)" : "Mantle Sepolia (5003)",
    commit,
    treeClean: !dirty,
    startedAt: startedAt.toISOString(),
    finishedAt: new Date().toISOString(),
    tag: a.tag,
    passed: !failed && steps.length === STEPS.length,
    steps,
    human,
    wallets: spent,
    transactions: txs.map(({ call: _, ...t }) => ({
      ...t,
      block: t.block.toString(),
      fee: formatEther(t.fee),
    })),
  };
  writeFileSync(join(dir, "results.json"), `${scrub(JSON.stringify(summary, null, 2))}\n`);
  const rows = txs.map(
    (t) =>
      `| ${t.item} | ${t.what} | ${t.status} | [${t.hash.slice(0, 10)}…${t.hash.slice(-4)}](${t.link}) | ${
        Object.entries(wallets).find(([, w]) => w.toLowerCase() === t.from.toLowerCase())?.[0] ??
        t.from
      } | ${formatEther(t.fee)} |`,
  );
  writeFileSync(
    join(dir, "transactions.md"),
    scrub(
      [
        "| Item | What | Status | Transaction | Sender | Fee (MNT) |",
        "| --- | --- | --- | --- | --- | ---: |",
        ...rows,
        "",
      ].join("\n"),
    ),
  );
  stopFork?.();

  // No secret in any file of the run (keystores hold keys only encrypted), no RPC URL in its logs.
  const secrets = a.secrets;
  for (const f of filesUnder(dir)) {
    if (f.endsWith(".sqlite") || f.endsWith(".sqlite-wal") || f.endsWith(".sqlite-shm")) continue;
    const text = readFileSync(f, "utf8").toLowerCase();
    for (const s of secrets) assert.ok(!text.includes(s), `a secret in ${f}`);
    if (!fork) assert.ok(!text.includes(upstream.toLowerCase()), `the RPC URL in ${f}`);
  }
  log(`no secret in the ${filesUnder(dir).length} files of ${dir}`);
  log(
    `${summary.passed ? "PASSED" : "FAILED"}: ${steps.filter((s) => s.ok).length}/${STEPS.length} steps, ${txs.length} transactions`,
  );
  process.exitCode = summary.passed ? 0 : 1;
}

for (const signal of ["SIGINT", "SIGTERM"] as const) {
  process.once(signal, () => {
    log(`${signal}: stopping`);
    void (a?.stop() ?? Promise.resolve()).finally(() => {
      stopFork?.();
      process.exit(130);
    });
  });
}

main().catch(async (e) => {
  log(`run failed: ${scrub(e instanceof Error ? (e.stack ?? e.message) : String(e))}`);
  await a?.stop();
  stopFork?.();
  process.exit(1);
});
